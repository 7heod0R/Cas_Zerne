-- Base de données du cas Zerne (SDIS 29)
CREATE DATABASE IF NOT EXISTS zerne CHARACTER SET utf8mb4;
USE zerne;

DROP TABLE IF EXISTS AVOIR_ACTIVITE;
DROP TABLE IF EXISTS PERIODE_GARDE;
DROP TABLE IF EXISTS DISPONIBILITE;
DROP TABLE IF EXISTS TRANCHE;
DROP TABLE IF EXISTS VOLONTAIRE;

-- Les pompiers volontaires du centre de secours
CREATE TABLE VOLONTAIRE (
    id INT PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    numeroBip VARCHAR(10) NOT NULL,
    nbGardes INT NOT NULL DEFAULT 0
);

-- Les quatre tranches horaires
CREATE TABLE TRANCHE (
    id INT PRIMARY KEY,
    libelle VARCHAR(30) NOT NULL
);

-- Une période de garde = une date + une tranche horaire
CREATE TABLE PERIODE_GARDE (
    idTranche INT NOT NULL,
    datePeriode DATE NOT NULL,
    nbPompiers INT NOT NULL,
    PRIMARY KEY (idTranche, datePeriode),
    FOREIGN KEY (idTranche) REFERENCES TRANCHE(id)
);

-- Les 3 niveaux de disponibilité
CREATE TABLE DISPONIBILITE (
    id INT PRIMARY KEY,
    libelle VARCHAR(30) NOT NULL
);

-- Disponibilité d'un volontaire pour une période de garde
CREATE TABLE AVOIR_ACTIVITE (
    idVolontaire INT NOT NULL,
    idTranche INT NOT NULL,
    datePeriode DATE NOT NULL,
    idDisponibilite INT NOT NULL,
    deGarde TINYINT NOT NULL DEFAULT 0,  -- 1 = désigné de garde, 0 sinon
    PRIMARY KEY (idVolontaire, idTranche, datePeriode),
    FOREIGN KEY (idVolontaire) REFERENCES VOLONTAIRE(id),
    FOREIGN KEY (idTranche, datePeriode) REFERENCES PERIODE_GARDE(idTranche, datePeriode),
    FOREIGN KEY (idDisponibilite) REFERENCES DISPONIBILITE(id)
);

